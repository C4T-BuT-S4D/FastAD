package run

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"net/url"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"text/template"

	"go.uber.org/zap"
	"gopkg.in/yaml.v3"
)

type simpleEnvTemplateContext struct {
	LogLevel      string
	PublicPort    int
	IntercomToken string

	DatabaseDSN              string
	TemporalPostgresUser     string
	TemporalPostgresPassword string
	TemporalPostgresDatabase string
	TemporalPostgresHost     string
	TemporalPostgresPort     string
	TemporalPostgresTLS      string
}

const simpleEnvTemplateData = `# FastAD simple preset environment file
# This file was generated by FastAD setup
# Do not edit this file manually

# allinone
FASTAD_LOG_LEVEL={{ .LogLevel }}
FASTAD_POSTGRES_DSN={{ .DatabaseDSN }}
FASTAD_INTERCOM_TOKEN={{ .IntercomToken }}

# temporal
TEMPORAL_POSTGRES_USER={{ .TemporalPostgresUser }}
TEMPORAL_POSTGRES_PASSWORD={{ .TemporalPostgresPassword }}
TEMPORAL_POSTGRES_DATABASE={{ .TemporalPostgresDatabase }}
TEMPORAL_POSTGRES_HOST={{ .TemporalPostgresHost }}
TEMPORAL_POSTGRES_PORT={{ .TemporalPostgresPort }}
TEMPORAL_POSTGRES_TLS={{ .TemporalPostgresTLS }}

# caddy
CADDY_PORT={{ .PublicPort }}
`

var simpleEnvTemplate = template.Must(template.New("simpleEnv").Parse(simpleEnvTemplateData))

func StartPresetSimple(ctx context.Context, root string, config *GameConfig) error {
	envPath := filepath.Join(root, ".env")
	envContext := simpleEnvTemplateContext{
		LogLevel:      config.FastAD.LogLevel,
		PublicPort:    config.FastAD.ListenPort,
		IntercomToken: config.FastAD.IntercomToken,
	}

	startPostgres := false
	if config.Database != nil && config.Database.ExternalDSN != "" {
		envContext.DatabaseDSN = config.Database.ExternalDSN
	} else {
		startPostgres = true
		envContext.DatabaseDSN = "postgres://fastad:fastad@postgres:5432/fastad?sslmode=disable"
	}

	startTemporalPostgres := false
	if config.Database != nil && config.Database.TemporalExternalDSN != "" {
		parsedDSN, err := url.Parse(config.Database.TemporalExternalDSN)
		if err != nil {
			return fmt.Errorf("parsing temporal external dsn: %w", err)
		}
		if parsedDSN.Scheme != "postgres" {
			return errors.New("temporal external dsn scheme must be postgres")
		}
		envContext.TemporalPostgresUser = parsedDSN.User.Username()
		envContext.TemporalPostgresPassword, _ = parsedDSN.User.Password()
		envContext.TemporalPostgresDatabase = parsedDSN.Path
		if strings.HasPrefix(parsedDSN.Path, "/") {
			envContext.TemporalPostgresDatabase = parsedDSN.Path[1:]
		}

		envContext.TemporalPostgresHost = parsedDSN.Hostname()
		envContext.TemporalPostgresPort = parsedDSN.Port()
	} else {
		startTemporalPostgres = true
		envContext.TemporalPostgresHost = "temporal-postgres"
		envContext.TemporalPostgresPort = "5432"
		//nolint:goconst // hardcoded values.
		envContext.TemporalPostgresUser = "temporal"
		envContext.TemporalPostgresPassword = "temporal"
		envContext.TemporalPostgresDatabase = "temporal"
		envContext.TemporalPostgresTLS = "false"
	}

	var envContent bytes.Buffer
	if err := simpleEnvTemplate.Execute(&envContent, envContext); err != nil {
		return fmt.Errorf("executing env template: %w", err)
	}
	if err := os.WriteFile(envPath, envContent.Bytes(), 0o644); err != nil {
		return fmt.Errorf("writing env file: %w", err)
	}

	composeContent, err := os.ReadFile(filepath.Join(
		root,
		"docker",
		"presets",
		"simple",
		"compose.yml",
	))
	if err != nil {
		return fmt.Errorf("reading compose file: %w", err)
	}

	var parsedCompose struct {
		Services map[string]any `yaml:"services"`
		Volumes  map[string]any `yaml:"volumes"`
	}
	if err := yaml.Unmarshal(composeContent, &parsedCompose); err != nil {
		return fmt.Errorf("unmarshalling compose file: %w", err)
	}

	if !startPostgres {
		delete(parsedCompose.Services, "postgres")
		delete(parsedCompose.Volumes, "fastad-db")

		if app, ok := parsedCompose.Services["app"].(map[string]any); ok {
			app["depends_on"] = map[string]any{
				"temporal": map[string]any{
					"condition": "service_healthy",
				},
			}
		}
	}

	if !startTemporalPostgres {
		delete(parsedCompose.Services, "temporal-postgres")
		delete(parsedCompose.Volumes, "temporal-db")

		if app, ok := parsedCompose.Services["app"].(map[string]any); ok {
			app["depends_on"] = nil
		}
	}

	checkersPath := config.Game.CheckersBasePath
	if !filepath.IsAbs(checkersPath) {
		checkersPath = filepath.Join(root, checkersPath)
	}

	if app, ok := parsedCompose.Services["app"].(map[string]any); ok {
		app["volumes"] = []string{
			fmt.Sprintf("%s:/checkers", checkersPath),
		}
	}

	// Set checkers base path to the mountpoint path.
	config.Game.CheckersBasePath = "/checkers"
	for _, service := range config.Services {
		service.Checker.Path = filepath.Join(config.Game.CheckersBasePath, service.Checker.Path)
	}

	rawCompose, err := yaml.Marshal(parsedCompose)
	if err != nil {
		return fmt.Errorf("marshalling compose file: %w", err)
	}

	destCompose := filepath.Join(root, "compose.yml")
	if err := os.WriteFile(destCompose, rawCompose, 0o644); err != nil {
		return fmt.Errorf("writing compose file: %w", err)
	}

	zap.L().Info("wrote compose file", zap.String("path", destCompose))

	zap.L().Info("stopping existing services")
	stopCmd := exec.CommandContext(ctx, "docker", "compose", "-f", destCompose, "down", "-v", "--remove-orphans")
	stopCmd.Dir = root
	stopCmd.Stdout = os.Stdout
	stopCmd.Stderr = os.Stderr
	if err := stopCmd.Run(); err != nil {
		return fmt.Errorf("stopping existing services: %w", err)
	}

	cmd := exec.CommandContext(ctx, "docker", "compose", "-f", destCompose, "up", "--build", "-d")
	cmd.Dir = root
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr

	zap.L().Info("starting services", zap.String("command", cmd.String()))
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("running docker compose: %w", err)
	}

	return nil
}
